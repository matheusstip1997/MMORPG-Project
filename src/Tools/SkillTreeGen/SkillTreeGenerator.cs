using System.Text.Json;
using Shared.Data;
using Shared.Data.Tables;

namespace SkillTreeGen;

/// <summary>
/// Builds the skill-tree tables from <c>docs/design/skill-trees.json</c> (spec 3.5 Implementation, WP-M2-5). Pure: it
/// reads text and returns text, so the round-trip test runs it on the committed files.
/// </summary>
public static class SkillTreeGenerator
{
    public const string GeneratedHeader = "Generated by src/Tools/SkillTreeGen from docs/design/skill-trees.json: do not edit (spec 3.5).";
    public const string AppendComment = "Appended by src/Tools/SkillTreeGen from docs/design/skill-trees.json (spec 3.5); edit freely, the generator never rewrites a row.";

    public sealed record DesignClass(string Id, string Name, string Parent, int Tier, int UnlockLevel, string Armor,
        string[] MainWeapons, string[] SecondaryWeapons);

    public sealed record DesignSkill(string Id, string ClassId, string Name, string Kind, int MaxLevel, int? MinLevel,
        string EvolvesFrom, (string Skill, int Level)[] Requires, string[] Weapons, string[] Elements, int Col, int Row);

    public static GenerationResult Generate(string designJson, TableFiles files, int maxTier)
    {
        var problems = new List<string>();
        var (classes, skills) = ReadDesign(designJson, problems);
        var settingsRows = files.Rows<SkillTreeSettings>(problems);
        var settings = settingsRows.Count == 1 ? settingsRows[0] : null;
        if (settings == null)
            problems.Add("SkillTreeSettings.json needs exactly one row");
        var classDefs = files.Rows<ClassDef>(problems);
        var gear = files.Rows<ClassGearDef>(problems);
        var strings = files.Rows<UiStrings>(problems);

        var byId = classes.ToDictionary(c => c.Id, StringComparer.Ordinal);
        var shipped = classes.Where(c => c.Tier <= maxTier).ToList();

        // Nodes: the trees of the shipped classes, class by class in design order, then by row and column.
        var nodes = new List<SkillTree>();
        var skillById = skills.ToDictionary(s => s.Id, StringComparer.Ordinal);
        foreach (var cls in shipped)
        {
            foreach (var skill in skills.Where(s => s.ClassId == cls.Id).OrderBy(s => s.Row).ThenBy(s => s.Col).ThenBy(s => s.Id, StringComparer.Ordinal))
            {
                if (settings == null)
                    break;
                var kind = ParseEnum<SkillNodeKind>(skill.Kind, $"skill '{skill.Id}' kind", problems);
                nodes.Add(new SkillTree
                {
                    Id = skill.Id,
                    Family = FamilyOf(skill, skillById, problems),
                    ClassId = skill.ClassId,
                    MinCharLevel = skill.MinLevel ?? settings.MinLevel(cls.Tier, cls.UnlockLevel, skill.Row),
                    Requires = skill.Requires.Select(r => r.Skill).ToArray(),
                    RequiresLevels = skill.Requires.Select(r => r.Level).ToArray(),
                    MaxLevel = kind == SkillNodeKind.WeaponUnlock ? settings.WeaponUnlockMaxLevel
                        : skill.MaxLevel > 0 ? skill.MaxLevel : settings.DefaultMaxLevel,
                    PointCost = settings.PointCostPerLevel,
                    Kind = kind,
                    EvolvesFrom = skill.EvolvesFrom,
                    Weapons = skill.Weapons.Select(w => ParseEnum<WeaponType>(w, $"skill '{skill.Id}' weapon", problems)).ToArray(),
                    Elements = skill.Elements.Select(e => ParseEnum<Element>(e, $"skill '{skill.Id}' element", problems)).ToArray(),
                    Row = skill.Row,
                    Col = skill.Col,
                });
            }
        }
        var evolutions = nodes.Where(n => n.EvolvesFrom.Length != 0)
            .Select(n => new SkillEvolution { NodeId = n.Id, Family = n.Family, ClassId = n.ClassId }).ToList();

        // Class rows: append the missing ones (numbers copied from the root, placeholders); check the design-owned fields.
        var classAppends = new List<string>();
        var gearAppends = new List<string>();
        int nextNetId = classDefs.Count == 0 ? 1 : classDefs.Max(c => c.NetId) + 1;
        foreach (var cls in shipped)
        {
            var armor = ArmorOf(cls, byId, problems);
            var existing = classDefs.FirstOrDefault(c => c.Id == cls.Id);
            if (existing == null)
            {
                var root = classDefs.FirstOrDefault(c => c.Id == RootOf(cls, byId).Id);
                if (root == null)
                {
                    problems.Add($"class '{cls.Id}': its root '{RootOf(cls, byId).Id}' has no ClassDef row to copy");
                    continue;
                }
                var row = CopyClass(root);
                row.Id = cls.Id;
                row.NetId = nextNetId++;
                row.Parent = cls.Parent;
                row.Tier = cls.Tier;
                row.UnlockLevel = cls.UnlockLevel;
                row.ArmorClass = armor;
                classAppends.Add(RowWriter.Write(row));
            }
            else
            {
                Expect(problems, $"ClassDef '{cls.Id}' parent", existing.Parent, cls.Parent);
                Expect(problems, $"ClassDef '{cls.Id}' tier", existing.Tier.ToString(), cls.Tier.ToString());
                Expect(problems, $"ClassDef '{cls.Id}' unlockLevel", existing.UnlockLevel.ToString(), cls.UnlockLevel.ToString());
                Expect(problems, $"ClassDef '{cls.Id}' armorClass", existing.ArmorClass.ToString(), armor.ToString());
            }

            // Root gear rows are the items WP's own (a starter weapon each); later tiers list the design's weapons.
            if (cls.Tier == 0)
                continue;
            var weapons = cls.MainWeapons.Concat(cls.SecondaryWeapons).Distinct()
                .Select(w => ParseEnum<WeaponType>(w, $"class '{cls.Id}' weapon", problems)).ToArray();
            var existingGear = gear.FirstOrDefault(g => g.Id == cls.Id);
            if (existingGear == null)
                gearAppends.Add(RowWriter.Write(new ClassGearDef { Id = cls.Id, WeaponTypes = weapons }));
            else
                Expect(problems, $"ClassGearDef '{cls.Id}' weaponTypes", string.Join(",", existingGear.WeaponTypes.OrderBy(w => w)),
                    string.Join(",", weapons.OrderBy(w => w)));
        }

        // Names: class.<id> and skillNode.<id>, from the design names; hand edits to the text stay.
        var stringAppends = new List<string>();
        var known = new HashSet<string>(strings.Select(s => s.Id), StringComparer.Ordinal);
        foreach (var cls in shipped)
        {
            if (known.Add(UiStringCoverage.ClassName(cls.Id)))
                stringAppends.Add(RowWriter.Write(new UiStrings { Id = UiStringCoverage.ClassName(cls.Id), Text = cls.Name }));
        }
        foreach (var node in nodes)
        {
            if (known.Add(UiStringCoverage.SkillNodeName(node.Id)))
                stringAppends.Add(RowWriter.Write(new UiStrings { Id = UiStringCoverage.SkillNodeName(node.Id), Text = skillById[node.Id].Name }));
        }

        var treeInfo = TableInfo.For(typeof(SkillTree));
        var evolutionInfo = TableInfo.For(typeof(SkillEvolution));
        return new GenerationResult(
            RowWriter.Table(treeInfo.Name, treeInfo.Version, new[]
            {
                GeneratedHeader,
                "One row per node of the roots' and the tier-1 classes' trees (user decision 2026-10-27). Numbers from",
                "SkillTreeSettings (placeholders): max level 5, weapon unlocks 1, 1 point per level, minimum level the class's",
                "unlock level + 4 (root trees) or 5 (later trees) per design row unless the design file sets one.",
            }, nodes),
            RowWriter.Table(evolutionInfo.Name, evolutionInfo.Version, new[]
            {
                GeneratedHeader,
                "One row per evolved node: its family (the root of its evolvesFrom chain) and its tree's class (R-3.5-04).",
            }, evolutions),
            classAppends, gearAppends, stringAppends, problems, nodes.Count, shipped.Count);
    }

    private static (List<DesignClass>, List<DesignSkill>) ReadDesign(string json, List<string> problems)
    {
        var classes = new List<DesignClass>();
        var skills = new List<DesignSkill>();
        using var document = JsonDocument.Parse(json, new JsonDocumentOptions { CommentHandling = JsonCommentHandling.Skip });
        var root = document.RootElement;
        if (!root.TryGetProperty("format", out var format) || format.GetString() != "mmorpg-skill-trees")
            problems.Add("the design file's format is not mmorpg-skill-trees");
        foreach (var c in root.GetProperty("classes").EnumerateArray())
        {
            classes.Add(new DesignClass(Str(c, "id"), Str(c, "name"), Str(c, "parent"), Int(c, "tier") ?? 0,
                Int(c, "unlockLevel") ?? 1, Str(c, "armor"), Strings(c, "mainWeapons"), Strings(c, "secondaryWeapons")));
        }
        foreach (var s in root.GetProperty("skills").EnumerateArray())
        {
            var requires = new List<(string, int)>();
            if (s.TryGetProperty("requires", out var list) && list.ValueKind == JsonValueKind.Array)
            {
                foreach (var r in list.EnumerateArray())
                    requires.Add((Str(r, "skill"), Int(r, "level") ?? 1));
            }
            skills.Add(new DesignSkill(Str(s, "id"), Str(s, "classId"), Str(s, "name"), Str(s, "kind"), Int(s, "maxLevel") ?? 0,
                Int(s, "minLevel"), Str(s, "evolvesFrom"), requires.ToArray(), Strings(s, "weapons"), Strings(s, "elements"),
                Int(s, "col") ?? 0, Int(s, "row") ?? 0));
        }
        return (classes, skills);
    }

    private static string FamilyOf(DesignSkill skill, Dictionary<string, DesignSkill> byId, List<string> problems)
    {
        var current = skill;
        for (int guard = 0; guard < 16; guard++)
        {
            if (current.EvolvesFrom.Length == 0)
                return current.Id;
            if (!byId.TryGetValue(current.EvolvesFrom, out var next))
            {
                problems.Add($"skill '{current.Id}' evolves from the unknown skill '{current.EvolvesFrom}'");
                return current.Id;
            }
            current = next;
        }
        problems.Add($"skill '{skill.Id}': its evolution chain loops");
        return skill.Id;
    }

    private static DesignClass RootOf(DesignClass cls, Dictionary<string, DesignClass> byId)
    {
        var current = cls;
        for (int guard = 0; guard < 8 && current.Parent.Length != 0 && byId.TryGetValue(current.Parent, out var parent); guard++)
            current = parent;
        return current;
    }

    /// <summary>R-3.5-08: a class keeps the tier of its earlier tier unless its own row sets one.</summary>
    private static ArmorClass ArmorOf(DesignClass cls, Dictionary<string, DesignClass> byId, List<string> problems)
    {
        var current = cls;
        for (int guard = 0; guard < 8; guard++)
        {
            if (current.Armor.Length != 0)
                return ParseEnum<ArmorClass>(current.Armor, $"class '{cls.Id}' armor", problems);
            if (current.Parent.Length == 0 || !byId.TryGetValue(current.Parent, out var parent))
                break;
            current = parent;
        }
        problems.Add($"class '{cls.Id}' has no armor tier on its line (R-3.5-08)");
        return ArmorClass.Light;
    }

    private static ClassDef CopyClass(ClassDef root)
    {
        var copy = new ClassDef();
        foreach (var field in TableInfo.For(typeof(ClassDef)).Fields)
            field.SetValue(copy, field.GetValue(root));
        return copy;
    }

    private static T ParseEnum<T>(string camel, string what, List<string> problems) where T : struct, Enum
    {
        foreach (var value in Enum.GetValues<T>())
        {
            if (ConfigTableReader.CamelCase(value.ToString()) == camel)
                return value;
        }
        problems.Add($"{what}: '{camel}' is not a {typeof(T).Name}");
        return default;
    }

    private static void Expect(List<string> problems, string what, string actual, string expected)
    {
        if (actual != expected)
            problems.Add($"{what} is '{actual}', the design file says '{expected}' (edit the row by hand)");
    }

    private static string Str(JsonElement e, string name) =>
        e.TryGetProperty(name, out var v) && v.ValueKind == JsonValueKind.String ? v.GetString() ?? string.Empty : string.Empty;

    private static int? Int(JsonElement e, string name) =>
        e.TryGetProperty(name, out var v) && v.ValueKind == JsonValueKind.Number ? v.GetInt32() : null;

    private static string[] Strings(JsonElement e, string name) =>
        e.TryGetProperty(name, out var v) && v.ValueKind == JsonValueKind.Array
            ? v.EnumerateArray().Where(x => x.ValueKind == JsonValueKind.String).Select(x => x.GetString()!).ToArray()
            : Array.Empty<string>();
}

/// <summary>What one generation produced: the two whole tables and the rows to append.</summary>
public sealed class GenerationResult
{
    public GenerationResult(string skillTree, string skillEvolution, List<string> classRows, List<string> gearRows,
        List<string> stringRows, List<string> problems, int nodeCount, int classCount)
    {
        SkillTreeText = skillTree;
        SkillEvolutionText = skillEvolution;
        ClassRows = classRows;
        GearRows = gearRows;
        StringRows = stringRows;
        Problems = problems;
        NodeCount = nodeCount;
        ClassCount = classCount;
    }

    public string SkillTreeText { get; }
    public string SkillEvolutionText { get; }
    public List<string> ClassRows { get; }
    public List<string> GearRows { get; }
    public List<string> StringRows { get; }
    public List<string> Problems { get; }
    public int NodeCount { get; }
    public int ClassCount { get; }

    /// <summary>What writing would change, one line per file.</summary>
    public List<string> Differences(TableFiles files)
    {
        var differences = new List<string>();
        if (!SameText(files.ReadText("SkillTree"), SkillTreeText))
            differences.Add($"{files.PathOf("SkillTree")} differs from the design file");
        if (!SameText(files.ReadText("SkillEvolution"), SkillEvolutionText))
            differences.Add($"{files.PathOf("SkillEvolution")} differs from the design file");
        if (ClassRows.Count > 0)
            differences.Add($"{files.PathOf("ClassDef")}: {ClassRows.Count} class row(s) to append");
        if (GearRows.Count > 0)
            differences.Add($"{files.PathOf("ClassGearDef")}: {GearRows.Count} gear row(s) to append");
        if (StringRows.Count > 0)
            differences.Add($"{files.PathOf("UiStrings")}: {StringRows.Count} name(s) to append");
        return differences;
    }

    public void Write(TableFiles files)
    {
        files.WriteText("SkillTree", SkillTreeText);
        files.WriteText("SkillEvolution", SkillEvolutionText);
        AppendTo(files, "ClassDef", ClassRows);
        AppendTo(files, "ClassGearDef", GearRows);
        AppendTo(files, "UiStrings", StringRows);
    }

    private static void AppendTo(TableFiles files, string table, List<string> rows)
    {
        var text = files.ReadText(table);
        if (text != null && rows.Count > 0)
            files.WriteText(table, JsoncAppender.Append(text, SkillTreeGenerator.AppendComment, rows));
    }

    private static bool SameText(string? a, string b) =>
        a != null && a.Replace("\r\n", "\n", StringComparison.Ordinal) == b.Replace("\r\n", "\n", StringComparison.Ordinal);
}
