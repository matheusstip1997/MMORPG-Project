#nullable enable
using System;
using System.Collections.Generic;
using Game.Gameplay.Entities;
using Game.UI.Auth;
using Game.UI.Config;
using Game.UI.Presenters;
using Shared.Data.Tables;
using UnityEngine;
using UnityEngine.InputSystem;
using UnityEngine.SceneManagement;
using UnityEngine.UIElements;

namespace Game.UI.Login
{
    /// <summary>
    /// Entry point of the login scene (<c>Assets/Game/UI/Login/Login.unity</c>, spec 9.10): loads the config tables,
    /// builds the four screens on a UI Toolkit panel scaled from the reference resolution (fit-height), signs in, and
    /// loads <c>LoginSettings.WorldScene</c> once the game connection is accepted. The scene is generated by
    /// <c>Editor/LoginSceneBuilder</c>. Sign-in uses the dev login in the editor and in builds with
    /// <c>MMORPG_DEV_LOGIN</c>, otherwise Steam (R-2.1-01).
    /// </summary>
    [RequireComponent(typeof(UIDocument))]
    public sealed class LoginRoot : MonoBehaviour
    {
        [Tooltip("Login screen styles (placeholder panels and text; spec 9.7 tokens).")]
        [SerializeField] private StyleSheet? styles;

#if UNITY_EDITOR || MMORPG_DEV_LOGIN
        [Tooltip("Dev login SteamID (ticket dev:<n>); the -devLogin <n> command line option overrides it.")]
        [SerializeField] private long devSteamId = 1;
#endif

        private readonly List<LoginPresenter> _presenters = new List<LoginPresenter>();
        private LoginFlow? _flow;
        private LoginPresenter? _title;
        private LoginPresenter? _servers;
        private LoginPresenter? _characters;
        private LoginPresenter? _create;
        private PanelSettings? _panel;
        private string _worldScene = "";
        private string _error = "";

        private void Awake()
        {
            if (!ClientConfig.TryLoad(out var tables, out var error))
            {
                Fail(error);
                return;
            }
            var config = LoginConfig.From(tables);
            _worldScene = config.Settings.WorldScene;

            var document = GetComponent<UIDocument>();
            ApplyScaling(document, config.Settings);

            var auth = new AuthApiClient(new UnityWebRequestAuthHttp(config.Settings.AuthRequestTimeoutMs), config.Settings.AuthApiUrl);
#if UNITY_EDITOR || MMORPG_DEV_LOGIN
            ILoginTicketSource tickets = DevLoginTicketSource.FromCommandLine(Environment.GetCommandLineArgs(), devSteamId);
#else
            ILoginTicketSource tickets = new SteamLoginTicketSource();
#endif
            _flow = new LoginFlow(config, auth, tickets, new ClientConnectionWorldConnector(), Application.version);
            _flow.ScreenChanged += ShowCurrentScreen;
            _flow.WorldReady += LoadWorld;
            _flow.ExitRequested += Quit;

            var root = document.rootVisualElement;
            root.AddToClassList("login-root");
            if (styles != null)
                root.styleSheets.Add(styles);
            _title = Add(root, new TitlePresenter(config, _flow));
            _servers = Add(root, new ServerSelectPresenter(config, _flow));
            _characters = Add(root, new CharacterSelectPresenter(config, _flow));
            _create = Add(root, new CharacterCreatePresenter(config, _flow));
            ShowCurrentScreen();
        }

        private void Start()
        {
            if (_flow != null)
                _ = _flow.SignInAsync();
        }

        private void Update()
        {
            if (_flow == null)
                return;
            _flow.Poll(); // may hand off and start loading the world (LoadWorld clears _flow)
            if (_flow != null && _flow.Screen == LoginScreen.Title && AnyButtonPressed())
                _flow.Continue();
        }

        private void OnDestroy()
        {
            foreach (var presenter in _presenters)
                presenter.Dispose();
            _presenters.Clear();
            _flow?.Dispose();
            _flow = null;
            if (_panel != null)
                Destroy(_panel);
        }

        private void OnGUI()
        {
            // Only for a broken setup (config tables), before any UI exists; the text is a developer message.
            if (_error.Length > 0)
                GUI.Label(new Rect(10, 10, Screen.width - 20, Screen.height - 20), _error);
        }

        /// <summary>
        /// Spec 9.7 / 9.10: reference resolution from config, scaled with the screen height. The document's panel
        /// settings asset is copied so play mode never writes into the asset.
        /// </summary>
        private void ApplyScaling(UIDocument document, LoginSettings settings)
        {
            if (document.panelSettings == null)
            {
                Fail("The UIDocument has no PanelSettings; rebuild the scene (MMORPG / UI / Rebuild Login Scene).");
                return;
            }
            _panel = Instantiate(document.panelSettings);
            _panel.scaleMode = PanelScaleMode.ScaleWithScreenSize;
            _panel.referenceResolution = new Vector2Int(settings.ReferenceWidth, settings.ReferenceHeight);
            _panel.screenMatchMode = PanelScreenMatchMode.MatchWidthOrHeight;
            _panel.match = settings.Scaling == UiScaleMode.FitHeight ? 1f : 0f;
            document.panelSettings = _panel;
        }

        private LoginPresenter Add(VisualElement root, LoginPresenter presenter)
        {
            presenter.Bind();
            root.Add(presenter.View.Root);
            _presenters.Add(presenter);
            return presenter;
        }

        private void ShowCurrentScreen()
        {
            if (_flow == null)
                return;
            _title?.View.SetVisible(_flow.Screen == LoginScreen.Title);
            _servers?.View.SetVisible(_flow.Screen == LoginScreen.ServerSelect);
            _characters?.View.SetVisible(_flow.Screen == LoginScreen.CharacterSelect);
            _create?.View.SetVisible(_flow.Screen == LoginScreen.CharacterCreate);
        }

        private static bool AnyButtonPressed()
        {
            var keyboard = Keyboard.current;
            var mouse = Mouse.current;
            var gamepad = Gamepad.current;
            return (keyboard != null && keyboard.anyKey.wasPressedThisFrame)
                   || (mouse != null && (mouse.leftButton.wasPressedThisFrame || mouse.rightButton.wasPressedThisFrame))
                   || (gamepad != null && (gamepad.buttonSouth.wasPressedThisFrame || gamepad.startButton.wasPressedThisFrame));
        }

        private void LoadWorld()
        {
            // The connection waits in WorldHandoff; nothing polls it until the world scene takes it.
            _flow?.Dispose();
            _flow = null;
#if UNITY_EDITOR
            // Works whether or not the scene is in the build settings.
            UnityEditor.SceneManagement.EditorSceneManager.LoadSceneInPlayMode(_worldScene, new LoadSceneParameters(LoadSceneMode.Single));
#else
            SceneManager.LoadScene(_worldScene);
#endif
        }

        private static void Quit()
        {
#if UNITY_EDITOR
            UnityEditor.EditorApplication.isPlaying = false;
#else
            Application.Quit();
#endif
        }

        private void Fail(string message)
        {
            _error = message;
            Debug.LogError($"[Login] {message}");
        }
    }
}
